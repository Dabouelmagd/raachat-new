-- الرقم بقى **اسمًا بديلًا للدخول** والكود بيروح لإيميل الحساب (الـSMS موقوف).
-- فلازم نفرّق بين رقم **أثبت صاحبه ملكيته** ورقم **مكتوب بالإيد**:
-- مطابقة جهات الاتصال والبحث بيشتغلوا على المتحقَّق بس، وإلا أي حد يدّعي رقم حد
-- تاني ويظهر مكانه في جهات اتصال كل اللي عندهم الرقم ده (تمثّل شخصية).
ALTER TABLE "User" ADD COLUMN "phoneVerifiedAt" TIMESTAMP(3);

-- **كل رقم موجود دلوقتي اتأكّد بـSMS فعلًا** — لأن الطريق الوحيد اللي بيحطّ رقمًا
-- على حساب كان `verifyOtp` بقناة `phone`، و`PATCH /me` عمره ما قبل `phone`.
-- فبنعلّمهم متحقَّقين: **صفر تغيير في سلوك الإنتاج** (الأرقام تفضل ظاهرة في
-- «الأصدقاء» زي ما هي)، والعمود يخصّ الأرقام الجديدة المكتوبة بالإيد وبس.
UPDATE "User" SET "phoneVerifiedAt" = "createdAt" WHERE "phone" IS NOT NULL;
