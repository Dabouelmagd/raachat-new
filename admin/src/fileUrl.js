/**
 * **رابط ملف مرفوع → رابط كامل يفتح من اللوحة.**
 *
 * `POST /uploads` بيرجّع الرابط من `PUBLIC_URL` — وهو **فاضي في الإنتاج**،
 * يعني الرابط بيطلع نسبيًا: `/uploads/<اسم>`. والملفات دي بيقدّمها **الـ API**
 * على دومينه، فالرابط النسبي جوه اللوحة بيتحلّ على **دومين اللوحة** — وCaddy
 * هناك بيردّ بصفحة اللوحة نفسها، فالصورة تطلع **مكسورة** بلا أي خطأ في
 * الكونسول ولا في لوج السيرفر (الطلب رجع ٢٠٠ أصلًا).
 *
 * حصل فعلًا (١٨ أكتوبر ٢٠٢٦): صورة الإعلان اترفعت بنجاح وما ظهرتش خالص.
 * التطبيق مكانش بيقع في ده لأن عنده `toAbs` في `api/client.ts` من الأول.
 *
 * دالة خالصة بلا أي استيراد — عشان تتجرّب لوحدها من غير بيئة Vite.
 */
export function fileUrl(url, base) {
  const u = (url || "").trim();
  if (!u.startsWith("/uploads/")) return u;   // رابط كامل أو فاضي: زي ما هو
  return (base || "").replace(/\/+$/, "") + u;
}
