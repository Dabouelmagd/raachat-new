#!/usr/bin/env bash
# عمر علامة نجاح الرفع على درايف — مصدر واحد للكتابة والقراءة.
#
# ليه موجود: `monitor.sh` بيفحص عمر النسخة **المحلية** بس، فلو الرفع على درايف
# وقف (التوكن اتلغي · درايف امتلا · الشبكة قطعت) النسخ المحلية تفضل سليمة
# والمراقبة تقول تمام، وكرون يكتب الخطأ في لوج محدش بيقراه، وأحدث نسخة على
# درايف **تقدم في سكوت** — والاكتشاف يوم ما السيرفر يموت، وهو بالظبط اليوم
# اللي النسخة موجودة عشانه.
#
# **وبلا أي نداء API من المراقبة** عن قصد: `rclone` كل ١٠ دقايق = ١٤٤ نداء في
# اليوم على مفتاح مشترك — نفس درس `$DC exec` مقابل `$DC run`. فالسكربت بيكتب
# العلامة والمراقبة بتفحص عمرها.
#
# 🔴 **والحكم على الوقت المكتوب جوّه الملف، مش على `mtime`:** أي `cp` أو `touch`
# أو استرجاع ملفات بيحدّث `mtime` للحظة دي، فعلامة عمرها شهر بتبان **طازة**
# والمراقبة تقول تمام على رفع واقف. والسطر اللي السكربت كتبه مابيكدبش على نفسه.
# نفس عائلة درس «لوج بيكدب في الوقت أسوأ من لوج بلا وقت».
#
# الشكل: "<epoch> <تاريخ UTC مقروء> <أسماء اللي اترفع>"
# الحقل الأول هو الحكم، والباقي للقراءة بالعين.

DRIVE_MARK=${DRIVE_MARK:-.drive-backup-ok}

# drive_mark_write "<وصف>" — بيكتب العلامة. بتتنادى **بعد** نجاح الرفع بس.
drive_mark_write() {
  printf '%s %s %s\n' "$(date -u +%s)" "$(date -u '+%F %T')UTC" "${1:-}" > "$DRIVE_MARK"
  chmod 600 "$DRIVE_MARK" 2>/dev/null || true
}

# drive_mark_age_h "<مسار العلامة>" → عدد الساعات، أو كلمة سبب:
#   missing = مفيش علامة خالص (الرفع عمره ما نجح من هنا)
#   bad     = الملف موجود وأول حقل فيه مش رقم (علامة مبهدلة — مش دليل نجاح)
#   future  = الوقت المكتوب في المستقبل (ساعة بايظة أو تعديل بالإيد)
# الرفض هو الحارس: علامة مابتتقراش **ماينفعش** تتحسب رفعًا ناجحًا.
drive_mark_age_h() {
  local f=${1:-$DRIVE_MARK} t now
  [ -f "$f" ] || { printf 'missing'; return 0; }
  t=$(head -1 "$f" 2>/dev/null | awk '{print $1}')
  case "$t" in
    ''|*[!0-9]*) printf 'bad'; return 0 ;;
  esac
  now=$(date -u +%s)
  if [ "$t" -gt "$now" ]; then printf 'future'; return 0; fi
  printf '%s' $(( (now - t) / 3600 ))
}
