#!/usr/bin/env bash
# يدوّر على **الملفات اليتيمة** في مجلد الرفع: ملف على القرص مفيش ولا صفّ في
# القاعدة بيشاور عليه (حساب اتمسح · رسالة اتحذفت · ستوري قديمة · رفع فشل).
#
#   على السيرفر:  cd /opt/rachat && bash scripts/orphan-files.sh
#   وللمسح:       cd /opt/rachat && bash scripts/orphan-files.sh --delete
#
# بدون `--delete` **مفيش حاجة بتتمسح** — تقرير وخلاص.
#
# ⚠️ **المسح مابيرجعش.** شوفي التقرير الأول، وبعدين امسحي.
#
# والحوارس (في `server/src/lib/orphanFiles.ts`، ومتفحوصة باختبارات):
#   • ملف أحدث من ٢٤ ساعة مابيتحسبش يتيمًا — الواجهة بترفع الملف قبل ما تبعت
#     الرسالة، فبين الخطوتين الملف بلا صفّ وهو سليم تمامًا.
#   • لو القاعدة رجّعت **صفر مرجع** وفيه ملفات، بيقف ومابيمسحش — ده شكل
#     استعلام بايظ وشكل قاعدة فاضية، ومن النتيجة مفيش طريق نفرّق.
#   • وبعد المسح بيتأكد إن الملفات **فعلًا** راحت.
set -euo pipefail
cd "$(dirname "$0")/.."
DC="docker compose -f docker-compose.prod.yml --env-file .env.production"
[ -f .env.production ] || { echo "❌ مفيش .env.production"; exit 1; }

DEL=0
if [ "${1:-}" = "--delete" ]; then
  DEL=1
  echo "⚠️ هتمسح الملفات اليتيمة **نهائيًا** — مفيش رجوع (والنسخة الاحتياطية بتاخد المرفوعات مرة في اليوم بس)."
  read -rp "متأكدة؟ اكتبي: yes أو نعم: " OK
  # ⚠️ السؤال بالعربي، فالإجابة الطبيعية «نعم» — وطلب كلمة إنجليزية هنا عيب
  # في السكربت مش حرص (و`set-sms-keys.sh` بيقبل العربي أصلًا، فده كان خروجًا
  # عن نمطنا). وفي نفس الوقت **مفيش `y` بحرف واحد**: الحذف مابيرجعش، فالكلمة
  # الكاملة احتكاك مقصود — والاحتكاك يبقى «اكتبي كلمة»، مش «اكتبيها إنجليزي».
  # --- confirm-case ---
  case "$OK" in
    yes|YES|Yes|نعم|أيوه|ايوه|ايوة|أيوة) ;;
    *) echo "تمام — مفيش حاجة اتمسحت."; exit 1;;
  esac
  # --- end confirm-case ---
fi

$DC exec -T -e RC_DELETE="$DEL" api node --input-type=module - < scripts/lib/orphanprobe.mjs
